/** 원래 목록 → 공개 목록 (빠진 것 없음, 변형은 of 가 붙음) */
export function curate(all: Tech[]): Tech[] {
  return all
    .filter((t) => !REMOVE.has(t.id))
    .map((t) => {
      const r = RENAME[t.id];
      const cat0 = MOVE[t.id] ?? t.cat;
      const cat = CAT_RENAME[cat0] ?? cat0;
      return { ...t, ...(r ?? {}), cat, ...(VARIANT_OF[t.id] ? { of: VARIANT_OF[t.id] } : {}) };
    });
}
